def scenario_accuracy(config: StudyConfig, scenario: str) -> torch.Tensor:
    """The generator's correctness table Λ_gen [R, K, G] for one scenario.

    The declared per-(annotator, category, region) probability that annotator r
    writes the consensus on a pixel of region g — the generator's own parameter,
    known by construction. Raises ValueError on an unknown scenario name: the
    study declares exactly the three scenarios r05 names and no fourth.
    """
    k, r, g = config.n_classes, config.n_annotators, config.n_regions
    if scenario == "region-varying":
        if r != len(S1_ACCURACY_MASS) or len(S1_ACCURACY_BOUNDARY) != r:
            raise ValueError("scenario 'region-varying' declares one mass and "
                             "one boundary accuracy per annotator")
        out = torch.empty(r, k, g, dtype=torch.float64)
        out[:, :, 0] = torch.tensor(S1_ACCURACY_MASS, dtype=torch.float64).view(
            r, 1).repeat(1, k)
        out[:, :, 1] = torch.tensor(S1_ACCURACY_BOUNDARY, dtype=torch.float64).view(
            r, 1).repeat(1, k)
        return out
    if scenario == "per-category":
        by_cat = torch.tensor(S2_ACCURACY_BY_CATEGORY, dtype=torch.float64)
        if k != by_cat.numel():
            raise ValueError("scenario 'per-category' declares one accuracy "
                             "per category")
        return by_cat.view(1, k, 1).repeat(r, 1, g)
    if scenario == "correlated-bias":
        return torch.full((r, k, g), S3_ACCURACY, dtype=torch.float64)
    raise ValueError(
        f"unknown scenario {scenario!r}; the study declares exactly "
        f"{list(SCENARIOS)}")


def true_reliability_table(lam_gen: torch.Tensor, prior: tuple) -> torch.Tensor:
    """Λ_true [R, K, G]: the agreement probability given the ANNOTATED category.

    The closed form under the generator's symmetric-noise process:

        Λ_true[r,k,g] = π_k Λ_gen[r,k,g]
                        / (π_k Λ_gen[r,k,g] + Σ_{c≠k} π_c (1−Λ_gen[r,c,g])/(K−1)).

    Computed exactly — nothing estimates it. Scenario 3's correlation is joint,
    so every per-annotator marginal — and this table with it — is unchanged
    there. Raises ValueError on a shape mismatch with the prior.
    """
    if not isinstance(lam_gen, torch.Tensor) or lam_gen.ndim != 3:
        raise ValueError(f"lam_gen must be [R, K, G]; got {lam_gen!r}")
    r_annotators, k, _ = lam_gen.shape
    if len(prior) != k:
        raise ValueError(f"prior must carry {k} categories; got {len(prior)}")
    pi = torch.tensor(prior, dtype=torch.float64)
    agree = pi.view(1, k, 1) * lam_gen                                      # [R, K, G]
    weighted = (1 - lam_gen) * pi.view(1, k, 1)                             # π_c (1−Λ_c)
    # Σ_{c≠k} π_c (1−Λ_gen[r,c,g])/(K−1): every wrong truth that lands on k,
    # which excludes the k-th term of the total flip mass.
    flip_in = (weighted.sum(dim=1, keepdim=True) - weighted) / (k - 1)      # [R, K, G]
    return agree / (agree + flip_in)


def generate_world(config: StudyConfig, scenario: str, seed: int) -> dict:
    """One synthetic world: crowd annotations, the fixed P proxy, known truth.

    Returns {"truth": [N] long, "region": [N] long, "labels": [R, N] long
    (filled with 0 where unannotated — the mask, not the label, decides what
    the estimators read), "mask": [R, N] bool, "P": [N, K], "Y": [R, N, K]
    one-hot of the annotations (every row one-hot; the mask decides what is
    read), "agree": [R, N] bool (y_r(n) = k*(n) — the generator's own knowledge
    of which annotations are wrong), "lam_gen": [R, K, G], "lam_true":
    [R, K, G], "scenario", "seed"}. Deterministic in (scenario, seed, config):
    every draw comes from one torch.Generator seeded with `seed`.
    """
    if not 0 < config.coverage <= 1:
        raise ValueError(f"coverage must lie in (0, 1]; got {config.coverage!r}")
    if abs(sum(config.prior) - 1) > 1e-9 or any(p <= 0 for p in config.prior):
        raise ValueError("prior must be a positive distribution")
    if abs(sum(config.region_split) - 1) > 1e-9:
        raise ValueError("region_split must sum to 1")
    lam_gen = scenario_accuracy(config, scenario)
    lam_true = true_reliability_table(lam_gen, config.prior)
    k, r, n = config.n_classes, config.n_annotators, config.n_pixels
    gen = torch.Generator().manual_seed(int(seed))

    # Consensus and regions: contiguous blocks in the declared split.
    truth = torch.multinomial(torch.tensor(config.prior, dtype=torch.float64),
                              n, replacement=True, generator=gen)
    n_mass = int(round(config.region_split[0] * n))
    region = torch.zeros(n, dtype=torch.long)
    region[n_mass:] = 1

    # The fixed segmentation proxy (what the warm-up froze): confident and
    # right w.p. 1 - e_g, confident and wrong at a uniformly-drawn other
    # category otherwise; the softness ε is a Dirichlet(1) residue either way,
    # drawn from this world's own generator (a Dirichlet(1) is a normalized
    # vector of unit-rate exponentials).
    model_wrong_rate = torch.where(
        region == 0,
        torch.tensor(config.model_error[0], dtype=torch.float64),
        torch.tensor(config.model_error[1], dtype=torch.float64))
    model_right = torch.rand(n, generator=gen) >= model_wrong_rate
    residue = -torch.log(torch.rand(n, k, generator=gen).clamp_min(1e-12))
    residue = residue / residue.sum(dim=-1, keepdim=True)
    p = torch.where(model_right.unsqueeze(-1), config.model_eps * residue,
                    (1 - config.model_eps) * residue)
    argmax_target = torch.where(
        model_right, truth,
        (truth + 1 + torch.randint(0, k - 1, (n,), generator=gen)) % k)
    p[torch.arange(n), argmax_target] += 1 - config.model_eps
    p = p / p.sum(dim=-1, keepdim=True)

    # Coverage and the symmetric-noise annotation process: write the consensus
    # w.p. Λ_gen[r, k*(n), g(n)], else one of the other K-1 uniformly.
    mask = torch.rand(r, n, generator=gen) < config.coverage
    lam_at_pixel = lam_gen[:, truth, region]                   # [R, N]
    agree = torch.rand(r, n, generator=gen) < lam_at_pixel
    if scenario == "correlated-bias":
        # ONE wrong category per pixel, shared by every annotator who flips
        # there: the joint is correlated, every marginal is unchanged.
        wrong = (truth + 1 + torch.randint(0, k - 1, (n,), generator=gen)) % k
        wrong = wrong.unsqueeze(0).repeat(r, 1)
    else:
        offsets = torch.randint(0, k - 1, (r, n), generator=gen)
        wrong = (truth.unsqueeze(0).repeat(r, 1) + 1 + offsets) % k
    y = torch.where(agree, truth.unsqueeze(0).repeat(r, 1), wrong)
    labels = torch.where(mask, y, torch.zeros((), dtype=torch.long))
    Y = torch.zeros(r, n, k, dtype=torch.float64)
    Y.scatter_(2, y.unsqueeze(-1), 1.0)
    return {"truth": truth, "region": region, "labels": labels, "mask": mask,
            "P": p, "Y": Y, "agree": agree, "lam_gen": lam_gen,
            "lam_true": lam_true, "scenario": scenario, "seed": int(seed)}


def estimate_thresholds(world: dict, config: StudyConfig) -> dict:
    """The warm-up estimation, shared by every candidate: EM → ρ̂_k → C̃_k.

    Eq. (3) estimated by the Dawid-Skene EM (`dawid_skene.fit_dawid_skene`),
    the confusion matrices it yields (C1's ρ_{r,k} source, per Eq. (5)), and
    Eq. (4)'s calibration C̃_k = max(1/K, F_k^{-1}(ρ̂_k)) over the fixed proxy
    P. A NaN ρ̂_k (a category the EM has no support for) is refused by
    `calibrate_cutoffs` — no threshold is invented here either.
    """
    k = config.n_classes
    em = fit_dawid_skene(world["labels"], world["mask"], k)
    rho_hat_k = rho_hat(em["posterior"], world["labels"], world["mask"], k)
    calibration = calibrate_cutoffs(world["P"], world["Y"],
                                    world["mask"].to(torch.float64), rho_hat_k)
    return {"em": em, "rho_hat": rho_hat_k, "cutoffs": calibration.cutoffs,
            "quantile": calibration.quantile, "clipped": calibration.clipped,
            "discarded": calibration.discarded,
            "flip_rates": flip_rates_from_confusions(em["confusions"])}


class RegionTableBranch(torch.nn.Module):
    """The pilot's φ: a per-(annotator, category, region) logit table.

    Λ_φ[r, n, k] = σ(θ[r, k, region(n)]). The declared truths live on exactly
    these cells, so this is the smallest branch that can express them: capacity
    is not the confound the pilot isolates, the constraint is. Init θ = 0
    (Λ = 0.5 everywhere). The image-conditioned branch the campaign trains is
    the campaign's design; this stand-in is declared in the premises.
    """

    def __init__(self, config: StudyConfig, region: torch.Tensor):
        super().__init__()
        if region.ndim != 1 or region.numel() < 1:
            raise ValueError(f"region must be a 1-D index tensor; got {region!r}")
        self.logits = torch.nn.Parameter(
            torch.zeros(config.n_annotators, config.n_classes, config.n_regions,
                        dtype=torch.float64))
        self._region = region

    def forward(self) -> torch.Tensor:
        # [R, K, G] -> [R, K, N] by per-pixel region -> [R, N, K].
        by_pixel = self.logits[:, :, self._region]
        return torch.sigmoid(by_pixel).permute(0, 2, 1)


def _evaluated_entries(world: dict):
    """Flatten the evaluated entries E = {(r,n): M=1} and their indices."""
    rows, cols = world["mask"].nonzero(as_tuple=True)
    labels_at = world["labels"][rows, cols]
    region_at = world["region"][cols]
    truth_at = world["truth"][cols]
    return rows, cols, labels_at, region_at, truth_at


def _gate_at_entries(world: dict, cutoffs: torch.Tensor) -> torch.Tensor:
    """The truncation gate 1[P[n, k_r] > C̃_{k_r}] at every evaluated entry."""
    rows, cols, labels_at, _, _ = _evaluated_entries(world)
    p_exp = world["P"].unsqueeze(0).expand(world["mask"].shape[0],
                                           *world["P"].shape)
    p_annot = p_exp[rows, cols, labels_at]
    return (p_annot > cutoffs.to(p_annot.dtype)[labels_at]).to(torch.float64)


def recovery_error(trained_lambda: torch.Tensor, world: dict) -> float:
    """Metric 1: mean |Λ_trained − Λ_true| over E, at the annotated slot.

    r05: "the recovery error of the trained reliability against the truth" —
    the truth being the generator's own agreement table `lam_true`, gathered
    at (annotator r, annotated category k_r, region g). Zero only for a field
    that recovers the truth exactly.
    """
    rows, cols, labels_at, region_at, _ = _evaluated_entries(world)
    trained_at = trained_lambda[rows, cols, labels_at]
    true_at = world["lam_true"][rows, labels_at, region_at]
    return float((trained_at - true_at).abs().mean())


def _pearson(a: torch.Tensor, b: torch.Tensor) -> float:
    """Pearson's correlation, NaN on a zero-variance input — reported, never
    invented: a constant field has no correlation with anything."""
    a = a.to(torch.float64)
    b = b.to(torch.float64)
    if bool(a.std() == 0) or bool(b.std() == 0):
        return float("nan")
    return float(torch.corrcoef(torch.stack([a, b]))[0, 1])


def gate_correlation(trained_lambda: torch.Tensor, world: dict,
                     cutoffs: torch.Tensor) -> float:
    """Metric 2: Pearson correlation between Λ_trained and the truncation gate.

    The gate is 1[P[n, k_r] > C̃_{k_r}] at every evaluated entry — the gate an
    unconstrained branch would merely reproduce (r05 § "The loss", Eq. (2)).
    """
    rows, cols, labels_at, _, _ = _evaluated_entries(world)
    trained_at = trained_lambda[rows, cols, labels_at]
    return _pearson(trained_at, _gate_at_entries(world, cutoffs))


def collapse_diagnosis(trained_lambda: torch.Tensor, world: dict) -> dict:
    """Metric 3's predicate: did the field degenerate, and how close was it.

    Returns {"collapsed": bool, "saturationFraction": the fraction of E within
    0.02 of 0 or 1, "fieldStd": the population standard deviation over E}. The
    declared predicate: collapsed ⟺ saturation ≥ 0.90 or std < 0.01.
    """
    rows, cols, labels_at, _, _ = _evaluated_entries(world)
    values = trained_lambda[rows, cols, labels_at].to(torch.float64)
    saturated = (values <= COLLAPSE_BOUNDARY) | (values >= 1 - COLLAPSE_BOUNDARY)
    saturation = float(saturated.to(torch.float64).mean())
    std = float(values.std())
    collapsed = (saturation >= COLLAPSE_SATURATION_FRACTION) or (std < COLLAPSE_STD_FLOOR)
    return {"collapsed": bool(collapsed), "saturationFraction": saturation,
            "fieldStd": std}


def pruning_precision_recall(trained_lambda: torch.Tensor, world: dict,
                             rho_hat_k: torch.Tensor) -> dict:
    """Metric 4: precision/recall of the pruning against known-wrong labels.

    Per category k: rank the category-k annotations by trained reliability
    ascending (stable order: (r, n) index), prune the first ⌈ρ̂_k · count_k⌉ —
    the budget Eq. (4) discards, identical for every candidate — and score
    against the annotations the generator knows are wrong (y ≠ k*). Returns
    the per-category lists and the micro-averaged pair. NaN where undefined:
    nothing pruned (precision), no wrong annotation in the category (recall).
    """
    rows, cols, labels_at, _, truth_at = _evaluated_entries(world)
    wrong_at = world["labels"][rows, cols] != truth_at
    trained_at = trained_lambda[rows, cols, labels_at].to(torch.float64)
    k = world["P"].shape[-1]
    per_category = []
    pruned_wrong_total = 0
    pruned_total = 0
    for cat in range(k):
        pick = labels_at == cat
        count = int(pick.sum())
        budget = int(torch.ceil(rho_hat_k[cat] * count)) if count else 0
        n_wrong = int(wrong_at[pick].sum())
        if budget and count:
            order = torch.argsort(trained_at[pick], stable=True)
            pruned_wrong = int(wrong_at[pick][order[:budget]].sum())
        else:
            pruned_wrong = 0
        precision = pruned_wrong / budget if budget else float("nan")
        recall = pruned_wrong / n_wrong if n_wrong else float("nan")
        per_category.append({"category": cat, "budget": budget,
                             "wrong": n_wrong, "prunedWrong": pruned_wrong,
                             "precision": precision, "recall": recall})
        pruned_wrong_total += pruned_wrong
        pruned_total += budget
    overall_wrong = int(wrong_at.sum())
    return {
        "perCategory": per_category,
        "precision": pruned_wrong_total / pruned_total if pruned_total else float("nan"),
        "recall": pruned_wrong_total / overall_wrong if overall_wrong else float("nan"),
        "prunedTotal": pruned_total,
    }


def floor_sensor(world: dict, thresholds: dict) -> dict:
    """The case-A sensor: F_k(1/K) per category after the warm-up.

    The fraction of category-k annotated confidences at or below the 1/K floor
    — Eq. (4)'s CDF at the clip — reported beside ρ̂_k and C̃_k: where
    F_k(1/K) > ρ̂_k the floor is discarding more than the noise estimate asks,
    and the difference is the over-discarding, by category. A property of the
    world and the warm-up, identical for every candidate.
    """
    k = world["P"].shape[-1]
    confidences = category_confidences(world["P"], world["Y"],
                                       world["mask"].to(torch.float64))
    floor = 1.0 / k
    f_floor = torch.tensor(
        [float((values <= floor).to(torch.float64).mean()) for values in confidences],
        dtype=torch.float64)
    return {"fFloor": f_floor.tolist(),
            "rhoHat": thresholds["rho_hat"].tolist(),
            "cutoffs": thresholds["cutoffs"].tolist(),
            "discarded": thresholds["discarded"].tolist(),
            "overDiscard": (f_floor - thresholds["rho_hat"]).tolist()}


def train_candidate(world: dict, thresholds: dict, config: StudyConfig,
                    candidate: str, lam: float | None = None) -> dict:
    """Train φ under ONE candidate on ONE world, segmentation held fixed.

    `candidate` is one of r05's three names ("C1", "C2", "C3") — anything else
    is refused, and a declared candidate's required parameter is required: C1
    needs the EM's ρ_{r,k} (Eq. 5's budget), C2 needs λ > 0, C3 needs neither.
    The branch is the declared per-(r, k, region) table; the objective is
    exactly the candidate's equation, with P, Y, M and the thresholds as
    constants — the segmentation is never a training target here.
    """
    if candidate not in ("C1", "C2", "C3"):
        raise ValueError(
            f"unknown candidate {candidate!r}; r05 declares exactly "
            "C1 (Ec. 5), C2 (Ec. 6) and C3 (Ec. 7)")
    branch = RegionTableBranch(config, world["region"])
    P, Y, M = world["P"], world["Y"], world["mask"].to(torch.float64)
    if candidate == "C1":
        objective = (lambda lam_tensor: c1_penalty(lam_tensor,
                                                   thresholds["flip_rates"]))
    elif candidate == "C2":
        if lam is None or not lam > 0:
            raise ValueError("candidate C2 requires the penalty weight λ > 0")
        objective = (lambda lam_tensor: c2_loss(P, Y, M, lam_tensor, lam))
    else:
        objective = lambda lam_tensor: c3_loss(P, Y, M, lam_tensor)
    return fit_reliability_branch(objective, branch, steps=config.branch_steps,
                                  lr=config.branch_lr)


def run_cell(config: StudyConfig, scenario: str, seed: int, candidate: str,
             lam: float | None = None) -> dict:
    """One run: declared world → warm-up estimation → candidate training →
    the four metrics. Returns the run's full record, its exact configuration
    included."""
    world = generate_world(config, scenario, seed)
    thresholds = estimate_thresholds(world, config)
    trained = train_candidate(world, thresholds, config, candidate, lam)
    metrics = {
        "recoveryError": recovery_error(trained["lambda"], world),
        "gateCorrelation": gate_correlation(trained["lambda"], world,
                                            thresholds["cutoffs"]),
        "collapse": collapse_diagnosis(trained["lambda"], world),
        "pruning": pruning_precision_recall(trained["lambda"], world,
                                            thresholds["rho_hat"]),
    }
    return {
        "scenario": scenario, "seed": int(seed), "candidate": candidate,
        "lambda": lam, "config": config.as_dict(),
        "metrics": metrics,
        "finalObjective": float(trained["finalObjective"]),
    }


def run_unconstrained_reference(config: StudyConfig, scenario: str,
                                seed: int) -> dict:
    """The unconstrained reference on one world: Eq. (2)'s analytic optimum.

    Not a candidate and trained by nobody: the pointwise minimizer of Eq. (1)
    over Λ with everything else fixed, which r05 § "The loss" states IS the
    truncation gate. Its metrics are the floor the candidates are read against:
    gate correlation 1 by construction, the recovery error of a pure gate,
    collapse by saturation.
    """
    world = generate_world(config, scenario, seed)
    thresholds = estimate_thresholds(world, config)
    gate = unconstrained_optimum(world["P"], world["Y"],
                                 world["mask"].to(torch.float64),
                                 thresholds["cutoffs"], config.q_unconstrained)
    metrics = {
        "recoveryError": recovery_error(gate, world),
        "gateCorrelation": gate_correlation(gate, world, thresholds["cutoffs"]),
        "collapse": collapse_diagnosis(gate, world),
        "pruning": pruning_precision_recall(gate, world, thresholds["rho_hat"]),
    }
    return {"scenario": scenario, "seed": int(seed), "candidate": "unconstrained",
            "lambda": None, "config": config.as_dict(), "metrics": metrics}


def truth_gate_correlation(config: StudyConfig, scenario: str, seed: int) -> float:
    """The truth's own correlation with the gate, on one world.

    The floor metric 2 can fall to before a candidate is suspected of merely
    reproducing the gate: a perfect recovery still correlates with the gate
    this much, because accurate annotators agree with an accurate model more
    often than not.
    """
    world = generate_world(config, scenario, seed)
    thresholds = estimate_thresholds(world, config)
    rows, cols, labels_at, region_at, _ = _evaluated_entries(world)
    lam_true_full = world["lam_true"][:, :, region_at].permute(0, 2, 1)
    true_at = lam_true_full[rows, cols, labels_at]
    return _pearson(true_at, _gate_at_entries(world, thresholds["cutoffs"]))
