"""The synthetic selection study r05 § "Falsifiable claim and assumptions"
declares under "Constraint selection (synthetic study)".

r05: "The identifiability of the reliability is checked, and the candidate
constraint selected, on synthetic ground truth where the true reliability of
every annotator, category and region is known: the candidates are (Ec. 5),
(Ec. 6) and (Ec. 7). The selection metrics are the recovery error of the
trained reliability against the truth, its correlation with the truncation gate
P > C̃_k that an unconstrained branch would merely reproduce, the collapse rate,
and the precision and recall of the pruning against annotations known to be
wrong. Until the study reports, no candidate is the design."

Everything here is the study's declared apparatus, shared by the three
candidates unchanged — same protocol, same data per (scenario, seed); the only
difference between candidates is the objective trained (and C2's declared λ
grid). It implements the four metrics and the warm-up sensor; it selects
nothing: the selection is closed by the deliberation in r06.

**The synthetic world.** K categories, R annotators, G region types, N pixels
partitioned into contiguous region blocks. Consensus k*(n) ~ π. The fixed
segmentation proxy P (what the warm-up froze): per pixel, with probability
1 − e_g the model's argmax is the consensus and P[n] = (1−ε)·onehot(k*) + ε·u
with u ~ Dirichlet(1); otherwise the argmax is a uniformly wrong category with
the same shape. Per annotator and pixel: coverage M_r(n) ~ Bernoulli(coverage);
the annotation is generated by the symmetric-noise process r05 states as the
reliability model — with probability Λ_gen[r, k*(n), g(n)] the annotator writes
the consensus, otherwise one of the other K−1 uniformly. Scenario 3 makes the
annotators' errors CORRELATED: one wrong category is drawn per pixel and every
annotator who flips there writes it — every per-annotator marginal is
unchanged, the joint is not, which is exactly the A1 violation the scenario
names ("sesgo correlacionado entre anotadores").

**The true reliability.** r05 § "The loss": Λ_r^k[w,h] is "the probability that
annotator r's annotation of category k at pixel (w,h) agrees with the
consensus", indexed by the ANNOTATED category. Under the generator that
probability follows in closed form from π and the generator's per-(r, category,
region) correctness Λ_gen: annotations of category k that agree are exactly the
truths k written correctly (mass π_k Λ_gen[r,k,g]); annotations of category k
that disagree come from truths c ≠ k flipping into k uniformly (mass
Σ_{c≠k} π_c (1−Λ_gen[r,c,g])/(K−1)). The ratio is the truth the recovery
metric measures against; `true_reliability_table` computes it exactly and
nothing estimates it. The generator's own correctness table Λ_gen is recorded
in every world so the deliberation can re-derive either reading.

**Scenarios (the three the study declares).**

1. "region-varying" — annotators are accurate on masses and degrade on thin
   boundaries; Λ_gen varies by REGION.
2. "per-category" — Λ_gen varies by CATEGORY.
3. "correlated-bias" — every annotator identical and moderate, and their flips
   land on the SAME wrong category per pixel.

**The metrics (r05's four, plus the warm-up sensor).** All are computed over
the evaluated entries E = {(r,n) : M_r(n) = 1} at the annotated slot k_r(n) —
the entries the loss reads — with the same population for every candidate.

1. `recovery_error` — mean |Λ_trained − Λ_true| over E.
2. `gate_correlation` — Pearson correlation between Λ_trained and the truncation
   gate 1[P[n, k_r] > C̃_{k_r}] over E. The unconstrained reference is the
   analytic optimum of Eq. (2) (`reliability.unconstrained_optimum`), which IS
   the gate; its correlation with the gate is 1 by construction. The truth's
   own correlation with the gate is reported beside it as the floor any honest
   recovery implies.
3. `collapse_diagnosis` — a declared predicate: a run collapses when at least
   90% of E's trained reliabilities sit within 0.02 of 0 or 1 (saturated), or
   the population standard deviation over E is below 0.01 (a dead field). The
   collapse RATE of a cell is the fraction of its seeds that collapse.
4. `pruning_precision_recall` — per category k, rank the category-k annotations
   by trained reliability ascending (stable order: (r, n) index — ties keep
   it, so the ranking is a function of the field alone), prune the first
   ⌈ρ̂_k · count_k⌉ — the fraction Eq. (4) discards, matched across candidates
   so precision and recall are comparable at an equal budget — and score the
   pruned set against the annotations the generator KNOWS are wrong (y ≠ k*).

**The warm-up sensor (the case-A sensor).** `floor_sensor`: F_k(1/K) per
category — the fraction of category-k annotated confidences at or below the
1/K floor, measured after the warm-up. Where F_k(1/K) exceeds ρ̂_k the 1/K clip
is discarding MORE than the noise estimate asks, and the difference is the
over-discarding, by category.

One module per mathematical object; `__provenance__` is read statically by
`implementation_cli.py verify` — the module is never imported to obtain it —
and it is the only thing that makes revision drift detectable.
"""

